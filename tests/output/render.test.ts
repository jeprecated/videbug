import { describe, expect, it } from "vitest";
import type { AnalysisProvenance, AnalysisSource, SubmitAnalysisPayload } from "../../src/contracts/analysis-v1.ts";
import { composeAnalysisResult } from "../../src/contracts/analysis-v1.ts";
import { evidenceRegistryFromEntries, validateAnalysisResult } from "../../src/contracts/validation.ts";
import { renderJson } from "../../src/output/json.ts";
import { renderMarkdown } from "../../src/output/markdown.ts";

const source: AnalysisSource = {
	basename: "recording.mp4",
	sha256: "a".repeat(64),
	durationMs: 2000,
	width: 1080,
	height: 1920,
	streamIndex: 0,
	averageFps: 30,
};

const provenance: AnalysisProvenance = {
	toolVersion: "0.0.0",
	ffmpegVersion: "8.1.1",
	analystModel: "anthropic/claude-opus-4-5",
	reviewerModel: "anthropic/claude-sonnet-4-5",
	inspectionCalls: 3,
	inspectedCells: 40,
	fullResolutionFrames: 2,
};

const FRAME_A = "v0_f000000_p000000_aaaaaa";
const FRAME_B = "v0_f000019_p001900_bbbbbb";

function payload(): SubmitAnalysisPayload {
	return {
		schemaVersion: "1",
		status: "complete",
		coverage: { analyzedStartMs: 0, analyzedEndMs: 2000, uninspectedRanges: [], confidence: "high" },
		summary: { observedFailure: "The session stack clears then restores.", chronology: "idle, cleared, restored" },
		beats: [
			{
				id: "B1",
				time: { startMs: 0, endMs: 1000, precisionMs: 100 },
				kind: "state",
				observation: { summary: "Idle session stack visible.", visibleText: ["Waiting"], motion: "none" },
				evidence: [{ frameId: FRAME_A, ptsMs: 0, role: "representative" }],
				confidence: "high",
				inferences: [],
			},
			{
				id: "B2",
				time: { startMs: 1000, endMs: 2000, precisionMs: 100 },
				kind: "transition",
				observation: { summary: "Stack cleared then restored.", visibleText: [], motion: "global-transition" },
				transitionFromPrevious: "Session Stack cleared",
				evidence: [{ frameId: FRAME_B, ptsMs: 1900, role: "boundary" }],
				confidence: "medium",
				inferences: [{ statement: "Likely a re-render race.", basis: "inference" }],
			},
		],
		anomalies: [
			{
				category: "contradictory-state",
				severity: "warning",
				description: "Stack cleared momentarily.",
				whySuspicious: "State reverted without user action.",
				beatIds: ["B2"],
				evidence: [{ frameId: FRAME_B, ptsMs: 1900, role: "boundary" }],
				confidence: "medium",
				uncertainties: ["Cause not visible."],
			},
		],
		handoff: {
			reproductionSteps: ["Open session stack.", "Wait for reload."],
			suggestedInvestigations: [{ statement: "Inspect stack reload logic.", kind: "action" }],
			uncertainties: ["Backend behavior not observable."],
		},
	};
}

function result() {
	return composeAnalysisResult(payload(), { source, provenance });
}

function registry() {
	return evidenceRegistryFromEntries([
		[FRAME_A, 0],
		[FRAME_B, 1900],
	]);
}

describe("renderJson", () => {
	it("emits pretty JSON with a trailing newline", () => {
		const json = renderJson(result());
		expect(json.endsWith("\n")).toBe(true);
		expect(json).toContain('"schemaVersion": "1"');
	});

	it("round-trips: parsed JSON re-validates against the semantic validator", () => {
		const json = renderJson(result());
		const parsed = JSON.parse(json);
		const check = validateAnalysisResult(parsed, { registry: registry() });
		expect(check.ok, check.ok ? "" : check.errors.join("\n")).toBe(true);
	});

	it("is a pure function of its input (stable output)", () => {
		expect(renderJson(result())).toBe(renderJson(result()));
	});
});

describe("renderMarkdown", () => {
	it("renders the observed failure, beats, anomalies, handoff and provenance", () => {
		const md = renderMarkdown(result());
		expect(md).toContain("# Debugging handoff");
		expect(md).toContain("The session stack clears then restores.");
		expect(md).toContain("B1");
		expect(md).toContain("Idle session stack visible.");
		expect(md).toContain("Session Stack cleared");
		expect(md).toContain("Stack cleared momentarily.");
		expect(md).toContain("Open session stack.");
		expect(md).toContain("Inspect stack reload logic.");
		// provenance footer includes the product name, model + counts, never secrets
		expect(md).toContain("Generated by videbug 0.0.0");
		expect(md).toContain("anthropic/claude-opus-4-5");
		expect(md).toContain("recording.mp4");
	});

	it("labels inferences distinctly from direct observation", () => {
		const md = renderMarkdown(result());
		expect(md).toMatch(/inference/i);
		expect(md).toContain("Likely a re-render race.");
	});

	it("renders mm:ss.mmm time ranges for beats", () => {
		const md = renderMarkdown(result());
		expect(md).toMatch(/00:00\.000/);
		expect(md).toMatch(/00:01\.000/);
	});

	it("is a pure function of its input (stable output)", () => {
		expect(renderMarkdown(result())).toBe(renderMarkdown(result()));
	});
});
